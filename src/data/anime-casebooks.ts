import type { AnimeSeriesId, Question, Quiz } from '../types'
import { animeQuizzes } from './anime'
import { originalArt, type OriginalScene } from './original-art'

type Case = [reference: number, scene: OriginalScene, prompt: string, options: Question['options'], explanation: string]

function casebook(series: AnimeSeriesId, title: string, entries: Case[]): Quiz {
  const base = animeQuizzes.find((quiz) => quiz.id === series)!
  const id = `${series}-casebook`
  return {
    ...base, id, title, difficulty: '困难', duration: 30,
    description: '读任务记录，找出设定错误。用已有剧情资料练习因果判断与信息核对。',
    tag: '原创配图 · 设定纠错',
    image: originalArt(entries[0][1]),
    scope: `${base.scope?.replace(/每题 \d+ 秒。?/g, '').trim()} 纠错专项，每题 30 秒。图片为原创主题示意图，不是作品场景。`,
    questions: entries.map(([reference, scene, prompt, options, explanation], index) => {
      const answer = index % 4
      const arranged: [string, string, string, string] = [...options]
      arranged[0] = options[answer]
      arranged[answer] = options[0]
      return {
        id: `${id}-${index + 1}`, prompt, options: arranged, answer,
        explanation, image: originalArt(scene), source: base.questions[reference - 1].source,
      }
    }),
  }
}

