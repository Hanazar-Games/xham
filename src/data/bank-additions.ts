import type { AnimeSeriesId, Question } from '../types'
import type { BankQuestion } from './question-banks'
import { animeQuizzes } from './anime'
import { originalArt, type OriginalScene } from './original-art'

type Entry = [reference: number, scene: OriginalScene, prompt: string, options: Question['options'], explanation: string]
function additions(series: AnimeSeriesId, entries: Entry[]): BankQuestion[] {
  const base = animeQuizzes.find((quiz) => quiz.series === series)!
  return entries.map(([reference, scene, prompt, choices, explanation], index) => {
    const answer = index % 4
    const options: [string, string, string, string] = [...choices]
    ;[options[0], options[answer]] = [options[answer], options[0]]
    return {
      id: `${series}-bank-${index + 1}`, difficulty: index < 6 ? '简单' : index < 11 ? '中等' : '困难',
      prompt, options, answer, explanation, image: originalArt(scene), source: base.questions[reference - 1].source,
    }
  })
}

