import { difficultySeconds, type Difficulty, type Question, type Quiz } from '../types'
import { animeQuizzes } from './anime'
import { animeSeries } from './anime-series'
import { originalArt, type OriginalScene } from './original-art'

type Entry = [reference: string, scene: OriginalScene, prompt: string, options: Question['options'], explanation: string]
const references = new Map(animeQuizzes.flatMap((quiz) => quiz.questions.map((question) =>
  [question.id, { question, series: animeSeries.find((series) => series.id === quiz.series)!.title }] as const,
)))
const positions = [2, 0, 3, 1, 0, 2, 1, 3, 1, 3, 2, 0]

function exam(id: string, title: string, description: string, difficulty: Difficulty, entries: Entry[]): Quiz {
  return {
    id, title, description, category: '二次元', series: 'crossover', difficulty,
    color: difficulty === '简单' ? 'mint' : 'lavender',
    duration: difficultySeconds[difficulty],
    tag: '跨番联考 · 原创配图', image: originalArt(id === 'crossover' ? 'connections' : entries[0][1]),
    scope: '跨番联考只并列考查原作品，不编造联动剧情。涉及鬼灭立志篇、火影寻找纲手之前及该篇章、Re:0 动画前两季、芙莉莲第一季、海贼王伙伴基础设定及吉卜力电影基础剧情。配图为原创主题示意图。',
    questions: entries.map(([reference, scene, prompt, options, explanation], index) => {
      const origin = references.get(reference)
      if (!origin?.question.source) throw new Error(`Missing crossover source: ${reference}`)
      const answer = positions[index]
      const arranged: [string, string, string, string] = [...options]
      arranged[0] = options[answer]
      arranged[answer] = options[0]
      return {
        id: `${id}-${index + 1}`, prompt: `【${origin.series}】${prompt}`,
        options: arranged, answer, explanation, source: origin.question.source, image: originalArt(scene),
      }
    }),
  }
}

